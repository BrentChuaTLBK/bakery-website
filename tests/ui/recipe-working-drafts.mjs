import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {blankRecipe} from '../../assets/ordering/recipe-model.js';
import {recipeBrowserHarness} from './recipe-audit-harness.mjs';
const t=await recipeBrowserHarness(),owner=t.h.ids.owner;
const api=(action,payload={})=>t.api(owner,action,payload);
try{
 const d=blankRecipe();d.name='Final with old working copies';d.variants[0].groups[0].ingredients=[{id:'flour',name:'Flour',quantity:'100',unit:'g'}];d.variants[0].methods[0].steps[0].instruction='Mix and bake.';
 let recipe=await api('create',{document:d,status:'final'});
 const old=randomUUID();
 await api('autosave',{draft_id:old,id:recipe.id,revision:recipe.revision,document:{...d,description:'Abandoned old copy'}});
 recipe=await api('save',{id:recipe.id,revision:recipe.revision,document:{...recipe.document,description:'Approved final'},status:'final'});
 const {page}=await t.pageFor(owner);page.setDefaultTimeout(15000);
 const library=async action=>{
  const start=t.requests.length;await action();
  await page.locator('.recipe-library').waitFor();
  await page.waitForFunction(()=>document.querySelector('[data-library-cost]')?.textContent&&!document.querySelector('[data-library-cost]').textContent.includes('Loading'));
  await page.waitForFunction(()=>document.querySelector('#recipe-main')?.getAttribute('aria-busy')!=='true');
  assert.ok(t.requests.slice(start).some(r=>r.action==='drafts'&&r.payload.current_only));
 };
 const noBanner=async()=>assert.equal(await page.locator('.recipe-draft-banner').count(),0);
 const edit=()=>page.locator('[data-action=edit-open]').click();
 const instruction=page.locator('[data-step-input]').first();
 const saved=()=>page.waitForFunction(()=>document.querySelector('#recipe-editor')?.inert===false&&document.querySelector('[data-save-status]')?.textContent.startsWith('Saved.'));
 await library(()=>page.goto(t.origin+'/recipes.html'));await noBanner();
 assert.equal(await page.locator('.recipe-card .recipe-badge').textContent(),'Final');
 for(let i=0;i<2;i++){await edit();await library(()=>page.locator('[data-action=keep-draft]').click());await noBanner();}
 assert.equal((await api('drafts')).length,1);assert.equal((await api('versions',{id:recipe.id})).length,2);
 console.log('PASS Old working copies and closing an unchanged Final recipe never show an unfinished banner.');
 await edit();await instruction.fill('Genuine pending changes');
 await library(()=>page.locator('[data-action=keep-draft]').click());
 await page.locator('.recipe-draft-banner').filter({hasText:'Unsaved changes'}).waitFor();
 assert.equal(await page.locator('.recipe-card .recipe-badge').textContent(),'Final');
 await page.getByRole('button',{name:'Resume working draft',exact:true}).click();
 assert.equal(await instruction.inputValue(),'Genuine pending changes');
 await page.locator('[data-action=save]').click();await saved();
 await library(()=>page.locator('[data-action=keep-draft]').click());await noBanner();
 assert.equal((await api('versions',{id:recipe.id})).length,3);
 assert.equal((await api('drafts')).length,1);
 await edit();await instruction.fill('Temporary change');
 await page.waitForFunction(()=>document.querySelector('[data-save-status]')?.textContent.startsWith('Working copy backed up.'));
 await instruction.fill('Genuine pending changes');
 await library(()=>page.locator('[data-action=keep-draft]').click());await noBanner();
 assert.equal((await api('drafts')).length,1);
 console.log('PASS Genuine changes remain recoverable; Save and edit/undo clear the current working copy without another recipe version.');
 // Cached library returns must recheck drafts saved in another tab.
 const staleSoon=randomUUID(),record=await api('get',{id:recipe.id});
 await api('autosave',{draft_id:staleSoon,id:record.id,revision:record.revision,document:{...record.document,description:'Other tab edit'}});
 await library(()=>page.locator('[data-action=refresh-library]').click());
 await page.locator('.recipe-draft-banner').waitFor();
 await page.locator('[data-action=open]').click();
 await api('save',{id:record.id,revision:record.revision,document:{...record.document,description:'Other tab saved'},status:'final'});
 await library(()=>page.locator('[data-action=library]').first().click());await noBanner();
 const before=await api('get',{id:recipe.id}),versions=await api('versions',{id:recipe.id});
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Recover working draft',exact:true}).click();
 await page.locator(`[data-action=recover-draft][data-id="${old}"]`).click();
 assert.match(await page.locator('#recipe-dialog').innerText(),/saved recipe is Final/);
 await page.locator('#recipe-dialog [data-action=discard-draft]').click();
 await page.locator('.site-dialog').getByRole('button',{name:'Cancel',exact:true}).click();
 assert.ok((await api('drafts')).some(d=>d.draft_id===old));
 await page.locator('#recipe-dialog [data-action=discard-draft]').click();
 await library(()=>page.locator('.site-dialog').getByRole('button',{name:'Discard draft',exact:true}).click());
 await noBanner();
 assert.equal((await api('drafts')).some(d=>d.draft_id===old),false);
 assert.equal((await api('drafts')).some(d=>d.draft_id===staleSoon),true);
 assert.deepEqual(await api('get',{id:recipe.id}),before);
 assert.deepEqual(await api('versions',{id:recipe.id}),versions);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 assert.deepEqual(t.errors,[]);
 console.log('PASS Cached navigation refreshes the banner, and mobile discard/cancel keeps saved recipes, history and other drafts intact.');
}finally{await t.close();}
