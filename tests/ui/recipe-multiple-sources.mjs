import assert from 'node:assert/strict';
import {join} from 'node:path';
import {recipeBrowserHarness} from './recipe-audit-harness.mjs';
const t=await recipeBrowserHarness(),owner=t.h.ids.owner;
const api=(action,payload={})=>t.api(owner,action,payload);
try{
 await api('save_recipe_unit',{name:'Tablespoon',symbol:'tbsp'});
 await api('save_recipe_unit',{name:'Scoop',symbol:'scoop'});
 const cream=await api('save_resource',{kind:'ingredient',name:'Whipping cream',data:{default_unit:'ml'},price:{amount:'200',quantity:'1000',unit:'ml'}});
 const juice=await api('save_resource',{kind:'ingredient',name:'Lemon juice',data:{default_unit:'g',unit_conversions:{tsp:{quantity:'4',unit:'g'}}},price:{amount:'20',quantity:'40',unit:'g'}});
 const {page}=await t.pageFor(owner);page.setDefaultTimeout(15000);
 await page.goto(t.origin+'/recipes.html');await page.locator('[data-tab=ingredient]').click();
 await page.locator('[data-action=add-resource]').click();
 const form=page.locator('#recipe-resource-form'),linked=form.locator('[data-linked-ingredient]'),rows=linked.locator('[data-yield-row]');
 await form.locator('[name=name]').fill('Homemade mascarpone');
 await form.getByRole('button',{name:'Add equivalent unit',exact:true}).click();
 const unit=form.locator('[data-conversion-from]');
 assert.equal(await unit.evaluate(el=>el.tagName),'SELECT');
 assert.equal(await unit.locator('option[value=tsp]').count(),1);
 assert.equal(await unit.locator('option[value=tbsp]').count(),1);
 assert.equal(await unit.locator('option[value=scoop]').count(),1);
 assert.equal(await unit.locator('option[value=kg]').count(),0,'Standard mass conversions do not need ingredient-specific equivalents');
 await unit.selectOption('scoop');await form.locator('[data-conversion-quantity]').fill('25');
 await linked.locator('[data-yield-mode]').selectOption('linked');
 assert.equal(await form.locator('[data-purchase-prices]').isVisible(),false);
 const choose=async(row,name)=>{await row.locator('[data-yield-search]').fill(name);await row.getByRole('option').filter({hasText:name}).click();};
 await choose(rows.nth(0),'Whipping cream');await rows.nth(0).locator('[data-yield-source-quantity]').fill('500');
 await linked.getByRole('button',{name:'+ Add ingredient',exact:true}).click();
 await choose(rows.nth(1),'Lemon juice');await rows.nth(1).locator('[data-yield-source-unit]').selectOption('tsp');await rows.nth(1).locator('[data-yield-source-quantity]').fill('1 1/2');
 await linked.locator('[data-yield-quantity]').fill('250');
 await linked.locator('[data-yield-preview]').filter({hasText:'Batch cost: ₱103.00'}).waitFor();
 await linked.locator('[data-yield-preview]').filter({hasText:'₱0.41 / g'}).waitFor();
 for(const width of [1440,390,320]){
  await page.setViewportSize({width,height:1000});
  assert.equal(await form.evaluate(el=>el.scrollWidth<=el.clientWidth+1),true,`No form overflow at ${width}px`);
  assert.equal(await rows.nth(1).locator('[data-yield-remove]').evaluate(el=>el.getBoundingClientRect().height>=40),true);
  if(width!==320)await linked.screenshot({path:join(t.out,`multiple-sources-${width}.png`)});
 }
 await form.getByRole('button',{name:'Save ingredient',exact:true}).click();await form.waitFor({state:'hidden'});
 let cheese=(await api('resources',{kind:'ingredient',query:'Homemade mascarpone'})).rows[0];
 assert.deepEqual(cheese.data.yield_source,{sources:[{ingredient_id:cream.id,source_quantity:'500',source_unit:'ml'},{ingredient_id:juice.id,source_quantity:'1.5',source_unit:'tsp'}],yield_quantity:'250',yield_unit:'g'});
 assert.equal(Number(cheese.price.amount),103);assert.deepEqual(cheese.data.unit_conversions,{scoop:{quantity:'25',unit:'g'}});
 const catalog=page.locator(`[data-resource-id="${cheese.id}"]`);await catalog.waitFor();assert.match(await catalog.innerText(),/2 ingredients → 250 g/);
 await catalog.locator('[data-action=edit-resource]').click();
 await page.waitForFunction(()=>document.querySelectorAll('[data-yield-search]')[1]?.value==='Lemon juice');
 assert.equal(await unit.inputValue(),'scoop');assert.equal(await rows.count(),2);
 assert.equal(await rows.nth(1).locator('[data-yield-source-unit]').inputValue(),'tsp');
 await linked.locator('[data-yield-preview]').filter({hasText:'₱103.00'}).waitFor();
 await linked.locator('[data-yield-mode]').selectOption('purchase');assert.equal(await form.locator('[data-purchase-prices]').isVisible(),true);
 await linked.locator('[data-yield-mode]').selectOption('linked');assert.equal(await rows.count(),2);
 await linked.getByRole('button',{name:'+ Add ingredient',exact:true}).click();
 await rows.nth(2).locator('[data-yield-search]').fill('Whipping cream');
 await rows.nth(2).getByText('No matching unused ingredients. Add the source ingredient to Ingredients first.').waitFor();
 await form.getByRole('button',{name:'Save ingredient',exact:true}).click();
 await page.locator('[data-dialog-error]').filter({hasText:'Select a saved source ingredient'}).waitFor();
 assert.equal((await api('resources',{kind:'ingredient',query:cheese.name})).rows[0].revision,cheese.revision);
 await rows.nth(2).locator('[data-yield-remove]').click();
 await rows.nth(1).locator('[data-yield-remove]').click();
 await linked.locator('[data-yield-preview]').filter({hasText:'Batch cost: ₱100.00'}).waitFor();
 assert.equal(await rows.nth(0).locator('[data-yield-remove]').isDisabled(),true);
 await form.getByRole('button',{name:'Save ingredient',exact:true}).click();await form.waitFor({state:'hidden'});
 cheese=(await api('resources',{kind:'ingredient',query:cheese.name})).rows[0];
 assert.equal(cheese.data.yield_source.ingredient_id,cream.id);assert.equal(Number(cheese.price.amount),100);
 console.log('PASS Multiple ingredients, fractional source units, combined cost, add/remove validation and save/reopen work at desktop and phone widths.');
 // Existing equivalents not registered in Manage are retained for safe editing.
 const legacy=await api('save_resource',{kind:'ingredient',name:'Legacy unit fixture',data:{default_unit:'g',unit_conversions:{ladle:{quantity:'50',unit:'g'}}}});
 await page.locator('[data-resource-search]').fill(legacy.name);
 await page.locator(`[data-resource-id="${legacy.id}"] [data-action=edit-resource]`).click();
 assert.equal(await unit.inputValue(),'ladle');assert.equal(await unit.locator('option[value=ladle]').textContent(),'ladle (saved unit)');
 assert.deepEqual(t.errors,[]);
 console.log('PASS Recipe-unit dropdown uses existing and custom units and retains previously saved equivalents.');
}finally{await t.close();}
